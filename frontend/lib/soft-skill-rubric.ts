export interface RubricLevel {
    key: keyof SkillRubric
    /** ค่าที่ระบบเก็บ (ActivitySoftSkill.rate / Evaluation) */
    value: 2 | 3 | 5
    label: string
    /** นิยามของระดับ (ใช้ข้อความเดียวกับ SOFT_SKILL_TIERS ที่แสดงในตัวเลือกระดับ) */
    meaning: string
    /**
     * กิจกรรมแบบไหนให้ระดับนี้ได้ — ต้องตรงกับ maxSoftSkillLevel (lib/soft-skills.ts และ backend/src/common/utils/soft-skill-cap.util.ts)
     * ถ้าแก้เพดานที่นั่น ต้องแก้ข้อความตรงนี้ด้วย
     */
    whenAllowed: string
}

